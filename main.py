def fetch_all_feeds() -> list:
    all_entries = []
    for name, url in RSS_FEEDS.items():
        try:
            feed = feedparser.parse(url)
            count = 0
            for entry in feed.entries:
                title = entry.get("title", "").strip()
                link = entry.get("link", "").strip()
                if not title or not link:
                    continue

                published_str = extract_published_time(entry)

                all_entries.append({
                    "id": make_news_id(entry),
                    "title": title,
                    "summary": strip_html(entry.get("summary", "") or entry.get("description", "")),
                    "link": link,
                    "source": name,
                    "published_time": published_str
                })
                count += 1
            log(f"📰 Fetched {count} entries from '{name}'.")
        except Exception as e:
            log(f"❌ Error fetching '{name}': {e}")
    return all_entries


def run_cycle() -> None:
    global LAST_RUN_STATS
    log("=" * 40)
    log("🚀 --- Starting scan cycle ---")
    log("=" * 40)
    current_time_str = datetime.now(IST).strftime("%d %b %Y, %I:%M %p")
    LAST_RUN_STATS["last_run_timestamp"] = current_time_str

    if not MODEL_NAME:
        log("🔍 Active model not found. Resolving Gemini...")
        resolve_gemini_model(force=True)

    # 1. Cycle shuru hone par Quota Exhaustion Check
    if gemini_budget_remaining() <= 0:
        LAST_RUN_STATS["quota_exhausted"] = True
        LAST_RUN_STATS["limit_type"] = "Local Daily Budget Reached"
        LAST_RUN_STATS["quota_value_at_exhaust"] = gemini_calls_used_today()
        LAST_RUN_STATS["exhaust_time"] = current_time_str
        log("🛑 Daily Gemini budget exhausted! Skipping cycle.")

        quota_hit_msg = (
            "🛑 *Daily Gemini Quota Limit Exhausted!*\n\n"
            f"Daily Limit: *{GEMINI_DAILY_CALL_BUDGET} calls*\n"
            f"Calls Used Today: *{gemini_calls_used_today()}*\n\n"
            "⚠️ Upper limit reach hone ke kaaran news scanning ruka hua hai.\n"
            "👉 Quota badhane ke liye neeche button par click karein:"
        )
        send_telegram_summary(quota_hit_msg, get_main_menu_keyboard())
        return

    log(f"📊 Budget remaining today: {gemini_budget_remaining()}/{GEMINI_DAILY_CALL_BUDGET} | Target Alerts: {MAX_ALERTS_PER_CYCLE}")

    entries = fetch_all_feeds()
    random.shuffle(entries)
    log(f"📰 Total {len(entries)} items collected and randomly shuffled.")

    if not entries:
        log("⚠️ No entries found in RSS feeds this cycle.")
        return

    new_alerts = 0
    items_evaluated = 0
    duplicate_count = 0
    pre_filtered_count = 0
    budget_exhausted_during_run = False

    for idx, entry in enumerate(entries, 1):
        if new_alerts >= MAX_ALERTS_PER_CYCLE:
            log(f"🛑 Target cap of {MAX_ALERTS_PER_CYCLE} alerts reached for this cycle.")
            break

        if items_evaluated >= MAX_ITEMS_TO_EVALUATE:
            log(f"⏹️ Checked safety ceiling of {MAX_ITEMS_TO_EVALUATE} items. Stopping scan.")
            break

        if is_news_processed(entry["id"]):
            duplicate_count += 1
            continue

        if not is_potentially_important(entry["title"]):
            mark_news_processed(entry["id"], entry["title"], entry["source"], "pre-filtered")
            pre_filtered_count += 1
            continue

        # 2. Mid-Cycle Quota Exhaustion Check
        if gemini_budget_remaining() <= 0:
            LAST_RUN_STATS["quota_exhausted"] = True
            LAST_RUN_STATS["limit_type"] = "Local Daily Budget Reached"
            LAST_RUN_STATS["quota_value_at_exhaust"] = gemini_calls_used_today()
            LAST_RUN_STATS["exhaust_time"] = datetime.now(IST).strftime("%d %b %Y, %I:%M %p")
            log("🛑 Daily Gemini budget ran out mid-cycle.")
            budget_exhausted_during_run = True

            send_telegram_summary(
                f"🛑 *Upper Limit Quota Hit ({GEMINI_DAILY_CALL_BUDGET}/{GEMINI_DAILY_CALL_BUDGET})!*\n\n"
                "Scan cycle beech me hi ruk gaya hai. Quota badhane ke liye Dashboard se '+ Add Gemini Quota' karein.",
                get_main_menu_keyboard()
            )
            break

        log("-" * 35)
        log(f"📌 Checking Item [{items_evaluated + 1}/{MAX_ITEMS_TO_EVALUATE}] | Alerts Sent: [{new_alerts}/{MAX_ALERTS_PER_CYCLE}]")
        log(f"   Headline: \"{entry['title']}\"")

        analysis = analyze_news(entry)

        if analysis is None:
            log("   ↳ ⚠️ Gemini analysis failed or timed out. Skipping.")
            continue

        items_evaluated += 1

        if analysis.upper().startswith("IGNORE"):
            mark_news_processed(entry["id"], entry["title"], entry["source"], "ignored")
            log("   ↳ 😴 Result: Evaluated as Routine/Low Impact (IGNORED)")
            continue

        log("   ↳ 🔥 Result: HIGH/MEDIUM IMPACT DETECTED! Sending to Telegram...")
        if send_telegram_alert(analysis, entry["link"], entry.get("published_time", "")):
            mark_news_processed(entry["id"], entry["title"], entry["source"], "sent")
            new_alerts += 1
            log("   ↳ ✅ Telegram Alert sent successfully!")
        else:
            mark_news_processed(entry["id"], entry["title"], entry["source"], "failed")
            log("   ↳ ❌ Telegram Alert dispatch failed.")

    LAST_RUN_STATS["duplicate_count"] = duplicate_count
    LAST_RUN_STATS["pre_filtered_count"] = pre_filtered_count
    LAST_RUN_STATS["sent_count"] = new_alerts

    log("=" * 40)
    log(f"📊 Summary: Duplicates={duplicate_count}, Pre-filtered Noise={pre_filtered_count}, AI Checked={items_evaluated}, Alerts Sent={new_alerts}")
    log("=" * 40)

    interval_display = format_interval_text(CHECK_INTERVAL_SECONDS)
    quota_reason_note = "\n⚠️ *Scan Quota Limit Reached hone par roka gaya.*" if budget_exhausted_during_run else ""

    closing_msg = (
        "🔄 *News Scan Completed*\n"
        f"✅ Alerts Sent: {new_alerts}\n"
        f"🛡️ Checked: {items_evaluated}\n"
        f"⚙️ Engine: `Gemini`\n"
        f"📊 Daily Quota Used: {gemini_calls_used_today()}/{GEMINI_DAILY_CALL_BUDGET}"
        f"{quota_reason_note}\n\n"
        f"Ab next >> news📢 tumhe *{interval_display}* ⏰ baad milegi. 👀"
    )
    send_telegram_summary(closing_msg)
    log(f"--- Cycle complete: {new_alerts} alerts sent ---")


