def analyze_news(entry: dict):
    global MODEL_NAME, LAST_RUN_STATS

    if not MODEL_NAME or gemini_budget_remaining() <= 0:
        return None

    prompt = ANALYSIS_PROMPT_TEMPLATE.format(
        title=entry["title"],
        summary=entry["summary"] or "N/A",
        source=entry["source"],
    )
    client = get_genai_client()
    models_to_try = [MODEL_NAME] + [m for m in GEMINI_MODEL_CANDIDATES if m != MODEL_NAME]

    for model_id in models_to_try:
        if gemini_budget_remaining() <= 0:
            break

        for attempt in range(1, GEMINI_MAX_RETRIES_PER_MODEL + 1):
            if gemini_budget_remaining() <= 0:
                return None
            try:
                log(f"⏳ Gemini [{model_id}] busy, processing... (Safety pause {API_PAUSE_SECONDS}s)")
                time.sleep(API_PAUSE_SECONDS)

                record_gemini_call()
                response = client.models.generate_content(model=model_id, contents=prompt)
                text = (getattr(response, "text", "") or "").strip()

                if not text:
                    raise ValueError("Empty response received from Gemini.")

                if model_id != MODEL_NAME:
                    MODEL_NAME = model_id
                    log(f"🔀 Switched active model to: '{model_id}'")

                return text

            except Exception as e:
                err_str = str(e)
                if "429" in err_str or "RESOURCE_EXHAUSTED" in err_str:
                    log(f"⚡ Google Gemini Quota Limit Triggered on [{model_id}]!")
                    if switch_to_backup_key():
                        client = get_genai_client()
                        continue
                    else:
                        LAST_RUN_STATS["quota_exhausted"] = True
                        LAST_RUN_STATS["limit_type"] = "Google 429 Hard Quota Hit"
                        LAST_RUN_STATS["quota_value_at_exhaust"] = gemini_calls_used_today()
                        LAST_RUN_STATS["exhaust_time"] = datetime.now(IST).strftime("%d %b %Y, %I:%M %p")
                else:
                    log(f"⚠️ Model [{model_id}] error on attempt {attempt}: {err_str[:80]}")
                time.sleep(attempt * 4)
                continue

    return None


