def resolve_gemini_model(force: bool = False) -> bool:
    global MODEL_NAME, _last_model_resolution_attempt

    if MODEL_NAME is not None:
        return True

    now = time.time()
    if not force and (now - _last_model_resolution_attempt) < GEMINI_RESOLUTION_COOLDOWN_SECONDS:
        return False
    _last_model_resolution_attempt = now

    if gemini_budget_remaining() <= 0:
        log("🛑 Daily Gemini budget exhausted during model resolution.")
        return False

    try:
        client = get_genai_client()
    except Exception as e:
        log(f"❌ Failed to initialize Google GenAI Client: {e}")
        return False

    log("🔍 Testing Gemini candidate models...")
    for candidate in GEMINI_MODEL_CANDIDATES:
        if gemini_budget_remaining() <= 0:
            break
        try:
            log(f"  ↳ Probing candidate model: '{candidate}'...")
            record_gemini_call()
            response = client.models.generate_content(
                model=candidate,
                contents="Reply with the single word: OK",
            )
            text = (getattr(response, "text", "") or "").strip()
            if text:
                MODEL_NAME = candidate
                log(f"✅ Gemini successfully connected! Active Model: '{candidate}'")
                return True
        except Exception as e:
            log(f"  ⚠️ Candidate '{candidate}' not reachable: {e}")
            time.sleep(2)
            continue
    log("❌ Could not resolve any working Gemini candidate model.")
    return False


