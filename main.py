def init_db() -> None:
    try:
        conn = sqlite3.connect(DB_PATH)
        cur = conn.cursor()
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS sent_news (
                news_id      TEXT PRIMARY KEY,
                title        TEXT,
                source       TEXT,
                status       TEXT,
                processed_at TEXT
            )
            """
        )
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS gemini_usage (
                usage_date  TEXT PRIMARY KEY,
                calls_used  INTEGER NOT NULL DEFAULT 0
            )
            """
        )
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS temp_quota (
                id INTEGER PRIMARY KEY CHECK (id = 1),
                calls_used INTEGER DEFAULT 0,
                start_time REAL DEFAULT 0,
                level_alerted INTEGER DEFAULT 0
            )
            """
        )
        cur.execute("INSERT OR IGNORE INTO temp_quota (id, calls_used, start_time, level_alerted) VALUES (1, 0, 0, 0)")
        conn.commit()
        conn.close()
        log("✅ Database initialized successfully.")
    except sqlite3.DatabaseError:
        if os.path.exists(DB_PATH):
            os.remove(DB_PATH)
        init_db()


def _today_utc_str() -> str:
    return datetime.now(timezone.utc).date().isoformat()


def gemini_calls_used_today() -> int:
    try:
        conn = sqlite3.connect(DB_PATH)
        cur = conn.cursor()
        cur.execute("SELECT calls_used FROM gemini_usage WHERE usage_date = ?", (_today_utc_str(),))
        row = cur.fetchone()
        conn.close()
        return row[0] if row else 0
    except sqlite3.Error:
        return 0


def track_and_check_quota_levels() -> None:
    try:
        conn = sqlite3.connect(DB_PATH)
        cur = conn.cursor()
        now = time.time()
        cur.execute("SELECT calls_used, start_time, level_alerted FROM temp_quota WHERE id = 1")
        row = cur.fetchone()

        if not row or row[1] == 0 or (now - row[1]) >= 86400:
            calls_used = 1
            start_time = now
            level_alerted = 0
            cur.execute(
                "UPDATE temp_quota SET calls_used = ?, start_time = ?, level_alerted = ? WHERE id = 1",
                (calls_used, start_time, level_alerted)
            )
        else:
            calls_used = row[0] + 1
            start_time = row[1]
            level_alerted = row[2]
            cur.execute("UPDATE temp_quota SET calls_used = ? WHERE id = 1", (calls_used,))

        conn.commit()
        conn.close()

        alert_msg = None
        new_level = level_alerted

        if calls_used >= 140 and level_alerted < 3:
            alert_msg = "You have crossed 🔥 HIgh Level 3 Quota"
            new_level = 3
        elif calls_used >= 90 and level_alerted < 2:
            alert_msg = "You have crossed 🌕 Mid Level 2 Quota"
            new_level = 2
        elif calls_used >= 45 and level_alerted < 1:
            alert_msg = "You have crossed 🌑 Low Level 1 Quota"
            new_level = 1

        if alert_msg and new_level > level_alerted:
            conn = sqlite3.connect(DB_PATH)
            cur = conn.cursor()
            cur.execute("UPDATE temp_quota SET level_alerted = ? WHERE id = 1", (new_level,))
            conn.commit()
            conn.close()
            send_telegram_summary(f"⚠️ *Quota Alert:*\n{alert_msg}\n*(Current Quota Used: {calls_used})*")

    except Exception as e:
        log(f"⚠️ Temp quota error: {e}")


def record_gemini_call() -> None:
    try:
        conn = sqlite3.connect(DB_PATH)
        cur = conn.cursor()
        today = _today_utc_str()
        cur.execute(
            """
            INSERT INTO gemini_usage (usage_date, calls_used) VALUES (?, 1)
            ON CONFLICT(usage_date) DO UPDATE SET calls_used = calls_used + 1
            """,
            (today,),
        )
        conn.commit()
        conn.close()
    except sqlite3.Error:
        pass
    track_and_check_quota_levels()


