def extract_published_time(entry) -> str:
    try:
        if hasattr(entry, "published_parsed") and entry.published_parsed:
            dt_utc = datetime(*entry.published_parsed[:6], tzinfo=timezone.utc)
            dt_ist = dt_utc.astimezone(IST)
            return dt_ist.strftime("%I:%M %p , %d %b")
        elif entry.get("published"):
            raw = entry.get("published").strip()
            return raw[:22]
    except Exception:
        pass
    return datetime.now(IST).strftime("%I:%M %p , %d %b")


def make_news_id(entry) -> str:
    news_id = entry.get("id") or entry.get("link")
